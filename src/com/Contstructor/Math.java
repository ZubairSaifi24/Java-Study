package com.Contstructor;

public class Math {

	//Default Constructor_''
	public Math() {	
		System.out.println("I am a default constructor");
	}
	
	//Parameterrized Constructor_''
	public Math(int x,int y) {
		System.out.println("\nI am parameterized Constructor");
		System.out.println("Sum : "+(x+y));
	}
	
}
